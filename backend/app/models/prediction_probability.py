"""
OraVisionAI — Prediction Probability Model

Normalized 7-class probability distribution per AI inference run.
"""

from __future__ import annotations

import decimal
import uuid
from typing import TYPE_CHECKING

from sqlalchemy import CheckConstraint, ForeignKey, Index, Numeric, SmallInteger, String, UniqueConstraint
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base

if TYPE_CHECKING:
    from app.models.ai_prediction import AIPrediction


class PredictionProbability(Base):
    """Discrete class probability generated by the 7-class EfficientNetB0 classifier."""

    __tablename__ = "prediction_probabilities"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )
    ai_prediction_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("ai_predictions.id", ondelete="CASCADE"),
        nullable=False,
    )
    class_name: Mapped[str] = mapped_column(
        String(100),
        nullable=False,
    )
    probability: Mapped[decimal.Decimal] = mapped_column(
        Numeric(5, 4),
        nullable=False,
    )
    class_index: Mapped[int] = mapped_column(
        SmallInteger,
        nullable=False,
    )

    __table_args__ = (
        UniqueConstraint("ai_prediction_id", "class_name", name="uq_prediction_class"),
        CheckConstraint(
            "probability >= 0.0 AND probability <= 1.0",
            name="chk_prob_range",
        ),
        Index("idx_pred_prob_prediction_id", "ai_prediction_id"),
    )

    # Relationships
    ai_prediction: Mapped[AIPrediction] = relationship(
        "AIPrediction",
        back_populates="probabilities",
    )

