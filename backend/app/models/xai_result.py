"""
OraVisionAI — Explainable AI (XAI) Result Model

Stores visual attention heatmaps and overlay artifacts generated by XAI algorithms (Grad-CAM, Occlusion, etc.).
"""

from __future__ import annotations

import datetime
import uuid
from typing import TYPE_CHECKING, Any, Dict, Optional

from sqlalchemy import Boolean, CheckConstraint, DateTime, ForeignKey, Index, String, Text, func
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base

if TYPE_CHECKING:
    from app.models.ai_prediction import AIPrediction
    from app.models.screening_image import ScreeningImage


class XAIResult(Base):
    """Visual explanation artifact generated to explain AI classification decisions."""

    __tablename__ = "xai_results"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )
    ai_prediction_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("ai_predictions.id", ondelete="CASCADE"),
        nullable=False,
    )
    screening_image_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("screening_images.id", ondelete="CASCADE"),
        nullable=False,
    )
    method: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
        index=True,
    )
    target_layer: Mapped[Optional[str]] = mapped_column(
        String(100),
        nullable=True,
    )
    is_primary_user_facing: Mapped[bool] = mapped_column(
        Boolean,
        default=False,
        nullable=False,
    )
    heatmap_storage_path: Mapped[str] = mapped_column(
        Text,
        nullable=False,
    )
    overlay_image_storage_path: Mapped[str] = mapped_column(
        Text,
        nullable=False,
    )
    parameters: Mapped[Optional[Dict[str, Any]]] = mapped_column(
        JSONB,
        nullable=True,
    )
    created_at: Mapped[datetime.datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )

    __table_args__ = (
        CheckConstraint(
            "method IN ('grad_cam', 'occlusion_sensitivity', 'score_cam', 'grad_cam_plus_plus', 'layer_cam', 'integrated_gradients')",
            name="chk_xai_method",
        ),
        Index("idx_xai_prediction_id", "ai_prediction_id"),
        Index("idx_xai_method", "method"),
        Index("idx_xai_primary", "ai_prediction_id", "is_primary_user_facing"),
    )

    # Relationships
    ai_prediction: Mapped[AIPrediction] = relationship(
        "AIPrediction",
        back_populates="xai_results",
    )
    screening_image: Mapped[ScreeningImage] = relationship(
        "ScreeningImage",
        back_populates="xai_results",
    )

